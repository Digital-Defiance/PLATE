"""Build the committed per-image diagnostic table for the real-artwork corpus.

Runs PLATE over every ``samples/real/*.png`` using the PUBLIC ``plate`` API and
writes ``docs/REAL-CORPUS.md`` with one row per image: PLATE object / anchor /
stroke / gradient counts, SSIM against a white and a dark background (when a
renderer is available), and the trace time in seconds.

This is diagnostic only: there are NO pass/fail thresholds and NO SSIM floors.
Intermediate SVGs are written to a temp dir and never under ``samples/``.

Run with the render extra:  python scripts/real_corpus_report.py
"""
from __future__ import annotations

import datetime as _dt
import tempfile
from pathlib import Path

import numpy as np

from plate import metrics, pipeline
from plate.config import load
from plate.imageio import open_rgba
from plate.raster import have_renderer

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / "samples" / "real"
DOC = ROOT / "docs" / "REAL-CORPUS.md"

INTRO = """# Real-artwork evaluation corpus

`samples/real/` is a deliberately messy, generated-realistic evaluation corpus
for PLATE. Its images exercise real-world stress axes the converter was **not**
tuned against: smooth multi-stop gradients and soft radial shading, soft drop
shadows / feathered edges / blur, mild sensor-style noise and JPEG-like block
artifacts, anti-aliased small text and thin strokes, busy palettes (>16 colours)
with near-duplicate colours, non-square and extreme aspect ratios, overlapping
semi-transparent shapes, and off-white textured backgrounds.

This corpus is a **diagnostic, not a gate**. There is no structural oracle
(`.target.svg`), no SSIM floor, and nothing here blocks CI. The independent
authored fixtures in `samples/challenges/` remain the structural oracle; these
images only show how PLATE behaves on messy inputs.

## Regenerate the images

```
PYTHONPATH=src DYLD_FALLBACK_LIBRARY_PATH=/opt/homebrew/lib \\
  .venv/bin/python scripts/make_real_corpus.py
```

The generator is deterministic (fixed per-image seeds), so re-running produces
byte-identical PNGs.

## Run the bench

```
PYTHONPATH=src DYLD_FALLBACK_LIBRARY_PATH=/opt/homebrew/lib \\
  .venv/bin/python -m plate bench samples/real -o out/real_bench
```

`bench` prints a PLATE-vs-VTracer table and writes `<stem>.plate.svg` /
`<stem>.vtracer.svg` into the output dir. Keep the output under `out/` or
`/tmp` so it is never staged.

## Rebuild this table

```
PYTHONPATH=src DYLD_FALLBACK_LIBRARY_PATH=/opt/homebrew/lib \\
  .venv/bin/python scripts/real_corpus_report.py
```

Provenance and the CC0 / public-domain drop-in manifest live in
[`samples/real/CREDITS.md`](../samples/real/CREDITS.md).

## Per-image diagnostics

Columns are PLATE output counts plus fidelity. `SSIM white` / `SSIM dark`
composite the source over a white and a near-black background respectively;
`-` means no renderer was available when the table was built.
"""


def main() -> int:
    renderer = have_renderer()
    cfg = load()
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = Path(tmp)
        for png in sorted(CORPUS.glob("real_*.png")):
            res = pipeline.run(png, cfg)
            (tmp_dir / f"{png.stem}.svg").write_text(res.svg, encoding="utf-8")
            m = metrics.analyze_svg(res.svg)
            ssim_w = ssim_d = "-"
            if renderer:
                rgba = np.asarray(open_rgba(png))
                fw = metrics.fidelity(res.svg, rgba, bg=(255, 255, 255))
                fd = metrics.fidelity(res.svg, rgba, bg=(16, 16, 16))
                ssim_w = f"{fw.get('ssim', '-')}"
                ssim_d = f"{fd.get('ssim', '-')}"
            rows.append((
                png.name,
                m["shapes"],
                m["anchors"],
                m["strokes"],
                m["gradients"],
                ssim_w,
                ssim_d,
                f"{res.stats['t_total']:.2f}",
            ))
            print(f"{png.name}: shapes={m['shapes']} anchors={m['anchors']} "
                  f"strokes={m['strokes']} gradients={m['gradients']} "
                  f"ssim_white={ssim_w} ssim_dark={ssim_d} t={rows[-1][7]}s")

    lines = [INTRO.rstrip(), ""]
    lines.append("| filename | objects | anchors | strokes | gradients | SSIM white | SSIM dark | seconds |")
    lines.append("|---|---:|---:|---:|---:|---:|---:|---:|")
    for r in rows:
        lines.append("| " + " | ".join(str(x) for x in r) + " |")
    lines.append("")
    stamp = _dt.date.today().isoformat()
    lines.append(f"_Table generated by `scripts/real_corpus_report.py` on {stamp}"
                 f" (renderer {'present' if renderer else 'absent'})._")
    lines.append("")

    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
