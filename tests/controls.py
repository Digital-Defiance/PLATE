"""Ground-truth contract for the CONTROL regression suite.

Shared by tests/test_controls.py. Each entry describes what PLATE is expected to
recover from the matching samples/controls/<name>.png (generated by
scripts/make_controls.py). The contract asserts the *editable structure* of the
output (object counts, primitive types, params within tolerance, layer names,
paint order, nesting) rather than exact pixels.

These expectations reflect PLATE's CURRENT verified behaviour. A few encode known
quirks on purpose so a future change that alters them trips a test and forces a
conscious decision (see NOTE comments). Update deliberately, never to paper over
a regression.

An `Obj` is one expected element in the flattened paint order (background first,
bottom -> top). Fields:
  kind     : expected Node.kind, or a set of acceptable kinds
  name     : exact expected layer name (None = don't care)
  params   : dict of primitive params to check within `tol` (abs tolerance in SVG px)
  min_anchors / max_anchors : bounds on the anchor count (catches primitive<->path drift)
  group_depth : how deeply nested this object is (0 = top level)
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Obj:
    kind: str | set[str]
    name: str | None = None
    params: dict = field(default_factory=dict)
    min_anchors: int | None = None
    max_anchors: int | None = None
    group_depth: int = 0
    grad_kind: str | None = None   # None = don't care; "linear" | "radial" = assert this fill


@dataclass
class Control:
    tier: str
    # expected top-level stats (None entries are skipped)
    shapes: int | None = None
    completed: int | None = None
    primitives: int | None = None
    max_total_anchors: int | None = None
    objects: list[Obj] = field(default_factory=list)
    ssim_floor: float = 0.90
    note: str = ""


# Default param tolerance in SVG px for primitive centres/radii.
TOL = 2.5
# Looser tolerance for angle (degrees) and for shapes near occluders.
